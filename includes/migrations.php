<?php
/**
 * Sistema de migrações incrementais.
 */

function migrations_table(PDO $pdo): string
{
    return table('migrations');
}

function ensure_migrations_table(PDO $pdo): void
{
    $t = migrations_table($pdo);
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS $t (
            id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name       VARCHAR(120) NOT NULL UNIQUE,
            applied_at TIMESTAMPTZ DEFAULT NOW()
        )"
    );
}

function applied_migrations(PDO $pdo): array
{
    ensure_migrations_table($pdo);
    $t = migrations_table($pdo);
    return $pdo->query("SELECT name FROM $t")->fetchAll(PDO::FETCH_COLUMN) ?: [];
}

function column_exists(PDO $pdo, string $table, string $column): bool
{
    $stmt = $pdo->prepare(
        'SELECT COUNT(*) FROM information_schema.columns
         WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?'
    );
    $stmt->execute([$table, $column]);
    return (int) $stmt->fetchColumn() > 0;
}

