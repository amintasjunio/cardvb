function pending_migrations(PDO $pdo): array
{
    $applied = applied_migrations($pdo);
    $list    = migrations_list();
    $pending = [];

    foreach ($list as $name => $mig) {
        if (!in_array($name, $applied, true)) {
            $pending[] = ['name' => $name, 'label' => $mig['label']];
        }
    }
    return $pending;
}

function run_migration(PDO $pdo, string $name): string
{
    $list = migrations_list();
    if (!isset($list[$name])) {
        throw new RuntimeException("Migração desconhecida: $name");
    }
    ensure_migrations_table($pdo);
    $message = ($list[$name]['run'])($pdo);
    $t = migrations_table($pdo);
    $stmt = $pdo->prepare("INSERT INTO $t (name) VALUES (?) ON CONFLICT (name) DO NOTHING");
    $stmt->execute([$name]);
    return $message;
}

function run_all_pending_migrations(PDO $pdo): array
{
    $results = [];
    foreach (pending_migrations($pdo) as $p) {
        $results[$p['name']] = run_migration($pdo, $p['name']);
    }
    return $results;
}