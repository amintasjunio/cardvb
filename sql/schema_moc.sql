  "id"         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name"       VARCHAR(120) NOT NULL UNIQUE,
  "applied_at" TIMESTAMPTZ DEFAULT NOW()
);

-- updated_at automático
DROP TRIGGER IF EXISTS "moc_profile_set_updated_at" ON "moc_profile";
CREATE TRIGGER "moc_profile_set_updated_at"
  BEFORE UPDATE ON "moc_profile"
  FOR EACH ROW EXECUTE FUNCTION "moc_set_updated_at"();

DROP TRIGGER IF EXISTS "moc_settings_set_updated_at" ON "moc_settings";
CREATE TRIGGER "moc_settings_set_updated_at"
  BEFORE UPDATE ON "moc_settings"
  FOR EACH ROW EXECUTE FUNCTION "moc_set_updated_at"();

