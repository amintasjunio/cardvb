-- Mantém updated_at em dia (substitui o ON UPDATE CURRENT_TIMESTAMP do MySQL)
CREATE OR REPLACE FUNCTION "moc_set_updated_at"() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS "moc_admin_users" (
  "id"            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "email"         VARCHAR(190) NOT NULL UNIQUE,
  "password_hash" VARCHAR(255) NOT NULL,
  "created_at"    TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS "moc_admin_sessions" (
  "token"      CHAR(64) PRIMARY KEY,
  "admin_id"   INT NOT NULL REFERENCES "moc_admin_users"("id") ON DELETE CASCADE,
  "expires_at" TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS "moc_admin_sessions_expires_idx" ON "moc_admin_sessions" ("expires_at");

CREATE TABLE IF NOT EXISTS "moc_profile" (
